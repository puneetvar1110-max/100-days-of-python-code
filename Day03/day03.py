# Topic: Positive, Negative or Zero Checker
# Description: Checks whether a number is positive, negative, or zero using if-elif-else statements.

number = int(input("Enter the number \n"))
if(number>0):
    print(number,"is a Positive Number")
elif(number==0):
    print(number,"is a Zero")
else:
    print(number,"is a Negative Number")

